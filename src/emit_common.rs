//! Pieces more than one emitter writes the same way.
//!
//! The Rust emitters share their type spelling, the TypeScript ones their
//! string literals and comments, and every source target its header. Each
//! lives here once, so the targets cannot drift apart on, say, the literal an
//! enum tag becomes in the TypeScript client and in its zod schema.

use std::fmt::Write;

use crate::ir::{Api, TypeRef};

/// The first lines of every generated source file, Rust and TypeScript alike:
/// both spell a line comment `//`.
pub(crate) const HEADER: &str = "// @generated by graphql-rpcgen. Source of truth: api/**/*.graphql
// DO NOT EDIT MANUALLY.
";

/// `description` as `///` lines, each prefixed with `indent`.
pub(crate) fn emit_doc_rust(out: &mut String, indent: &str, description: &Option<String>) {
    let Some(text) = description else { return };
    for line in text.lines() {
        let _ = writeln!(out, "{indent}/// {line}");
    }
}

/// `description` as a JSDoc block, each line prefixed with `indent`: on one
/// line for a one-line description, the starred form otherwise.
pub(crate) fn emit_doc_jsdoc(out: &mut String, indent: &str, description: &Option<String>) {
    let Some(text) = description else { return };
    let one_line = text.lines().count() == 1;
    if one_line {
        let _ = writeln!(out, "{indent}/** {text} */");
        return;
    }
    let _ = writeln!(out, "{indent}/**");
    for line in text.lines() {
        let _ = writeln!(out, "{indent} * {line}");
    }
    let _ = writeln!(out, "{indent} */");
}

/// A TypeScript string literal holding `value`.
///
/// Single-quoted to match the rest of the emitted files, with the characters
/// that would end the literal early escaped. Wire vocabularies are not chosen
/// by this compiler — `@variant(tag:)` takes whatever the other end calls a
/// thing, apostrophe included — so the quoting has to survive one.
pub(crate) fn quoted(value: &str) -> String {
    let escaped = value
        .replace('\\', "\\\\")
        .replace('\'', "\\'")
        .replace('\n', "\\n")
        .replace('\r', "\\r");
    format!("'{escaped}'")
}

/// The Rust type of a value of `ty`: `Option` for a nullable one.
pub(crate) fn rust_type(api: &Api, ty: &TypeRef) -> String {
    let inner = rust_type_non_null(api, ty);
    if ty.is_nullable() {
        format!("Option<{inner}>")
    } else {
        inner
    }
}

/// The Rust type of a value of `ty` that is present.
pub(crate) fn rust_type_non_null(api: &Api, ty: &TypeRef) -> String {
    match ty {
        TypeRef::Named { name, .. } => scalar_rust_name(api, name),
        TypeRef::List { inner, .. } => format!("Vec<{}>", rust_type(api, inner)),
    }
}

/// The Rust name of the type named `name`: a scalar's mapping, or the SDL name
/// itself for every type this crate emits.
fn scalar_rust_name(api: &Api, name: &str) -> String {
    match api.find_scalar(name) {
        // A newtype scalar is referred to by its own name; the inner
        // representation only appears in the wrapper's definition.
        Some(s) if s.rust_newtype => s.name.clone(),
        Some(s) => s.rust.clone(),
        None => name.to_string(),
    }
}

/// The stem of an operation's `wire` statics: `FILES_WATCH` for `Files.watch`,
/// before `_FIELDS`, `_HTTP` or `_TYPES`.
pub(crate) fn fields_static_name(service: &str, operation: &str) -> String {
    format!(
        "{}_{}",
        crate::naming::snake_case_raw(service),
        crate::naming::snake_case_raw(operation)
    )
    .to_uppercase()
}

/// `prefix{a, b, ..};` on one line, the items sorted and braces only around
/// more than one; empty for no items. `rustfmt` lays it out.
pub(crate) fn use_list(prefix: &str, items: &[&str]) -> String {
    let mut items: Vec<&str> = items.to_vec();
    items.sort_unstable();
    match items.as_slice() {
        [] => String::new(),
        [one] => format!("{prefix}{one};\n"),
        many => format!("{prefix}{{{}}};\n", many.join(", ")),
    }
}

/// `pub use {path}::{items};` for the items whose name the API does not give
/// a type of its own; empty when none is left.
///
/// A re-export beside the API's types must not be spelt like one: in the
/// module that declares them it is a duplicate item, and in one that
/// glob-imports them it shadows the type wherever the module names it. The
/// generated code itself never needs the re-export — it names the runtime's
/// items by their absolute paths — so a caller of a module that leaves one
/// out names it by its path as well.
pub(crate) fn reexport(api: &Api, path: &str, items: &[&str]) -> String {
    let kept: Vec<&str> = items
        .iter()
        .copied()
        .filter(|item| api.find_type(item).is_none())
        .collect();
    use_list(&format!("pub use {path}::"), &kept)
}
